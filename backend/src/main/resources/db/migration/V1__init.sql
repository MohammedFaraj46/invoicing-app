-- V1__init: initial schema for the invoicing app.
-- Money: numeric(12,2). Quantities: numeric(12,3). Rates: numeric(5,2).
-- Enums are stored as varchar with CHECK constraints so the values stay
-- readable in the database and can be extended with a later migration.

-- ---------------------------------------------------------------------------
-- app_user ("user" is a reserved word in Postgres)
-- ---------------------------------------------------------------------------
CREATE TABLE app_user (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         varchar(255) NOT NULL,
    password_hash varchar(255) NOT NULL,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_user_email UNIQUE (email)
);

-- ---------------------------------------------------------------------------
-- company (one-to-one with user)
-- ---------------------------------------------------------------------------
CREATE TABLE company (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                   bigint       NOT NULL,
    name                      varchar(255) NOT NULL,
    kvk_number                varchar(20)  NOT NULL,
    vat_number                varchar(20)  NOT NULL,
    address_line              varchar(255) NOT NULL,
    postal_code               varchar(20)  NOT NULL,
    city                      varchar(100) NOT NULL,
    country                   varchar(2)   NOT NULL DEFAULT 'NL',
    default_payment_term_days int          NOT NULL DEFAULT 30,
    logo_url                  varchar(512),
    CONSTRAINT uq_company_user UNIQUE (user_id),
    CONSTRAINT fk_company_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT ck_company_payment_term_positive CHECK (default_payment_term_days > 0)
);

-- ---------------------------------------------------------------------------
-- customer
-- ---------------------------------------------------------------------------
CREATE TABLE customer (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id   bigint       NOT NULL,
    name         varchar(255) NOT NULL,
    email        varchar(255) NOT NULL,
    vat_number   varchar(20),
    address_line varchar(255) NOT NULL,
    postal_code  varchar(20)  NOT NULL,
    city         varchar(100) NOT NULL,
    country      varchar(2)   NOT NULL,
    CONSTRAINT fk_customer_company FOREIGN KEY (company_id) REFERENCES company (id)
);

CREATE INDEX ix_customer_company ON customer (company_id);

-- ---------------------------------------------------------------------------
-- invoice
-- ---------------------------------------------------------------------------
CREATE TABLE invoice (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id        bigint         NOT NULL,
    customer_id       bigint         NOT NULL,
    invoice_number    varchar(50),
    status            varchar(20)    NOT NULL,
    invoice_date      date,
    due_date          date,
    payment_term_days int            NOT NULL,
    subtotal_amount   numeric(12, 2) NOT NULL DEFAULT 0,
    vat_amount        numeric(12, 2) NOT NULL DEFAULT 0,
    total_amount      numeric(12, 2) NOT NULL DEFAULT 0,
    currency          varchar(3)     NOT NULL DEFAULT 'EUR',
    notes             varchar(1000),
    sent_at           timestamptz,
    paid_at           timestamptz,
    created_at        timestamptz    NOT NULL DEFAULT now(),
    updated_at        timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT fk_invoice_company  FOREIGN KEY (company_id)  REFERENCES company (id),
    CONSTRAINT fk_invoice_customer FOREIGN KEY (customer_id) REFERENCES customer (id),
    CONSTRAINT ck_invoice_status CHECK (status IN ('DRAFT', 'SENT', 'PAID', 'OVERDUE')),
    CONSTRAINT ck_invoice_payment_term_positive CHECK (payment_term_days > 0),
    -- a draft has no number or date yet; anything past DRAFT must have both
    CONSTRAINT ck_invoice_number_when_sent CHECK (
        status = 'DRAFT' OR (invoice_number IS NOT NULL AND invoice_date IS NOT NULL)
    )
);

-- unique per company; the number itself carries the year (e.g. 2026-0001)
CREATE UNIQUE INDEX uq_invoice_number_per_company
    ON invoice (company_id, invoice_number)
    WHERE invoice_number IS NOT NULL;

CREATE INDEX ix_invoice_company  ON invoice (company_id);
CREATE INDEX ix_invoice_customer ON invoice (customer_id);

-- ---------------------------------------------------------------------------
-- invoice_line
-- ---------------------------------------------------------------------------
CREATE TABLE invoice_line (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id      bigint         NOT NULL,
    position        int            NOT NULL,
    description     varchar(500)   NOT NULL,
    quantity        numeric(12, 3) NOT NULL,
    unit_price      numeric(12, 2) NOT NULL,
    vat_rate        numeric(5, 2)  NOT NULL,
    vat_type        varchar(20)    NOT NULL,
    line_net_amount numeric(12, 2) NOT NULL,
    line_vat_amount numeric(12, 2) NOT NULL,
    line_total      numeric(12, 2) NOT NULL,
    CONSTRAINT fk_invoice_line_invoice FOREIGN KEY (invoice_id)
        REFERENCES invoice (id) ON DELETE CASCADE,
    CONSTRAINT ck_invoice_line_vat_type CHECK (
        vat_type IN ('STANDARD', 'REDUCED', 'ZERO', 'REVERSE_CHARGE')
    ),
    CONSTRAINT ck_invoice_line_vat_rate CHECK (vat_rate >= 0),
    CONSTRAINT uq_invoice_line_position UNIQUE (invoice_id, position)
);

CREATE INDEX ix_invoice_line_invoice ON invoice_line (invoice_id);

-- ---------------------------------------------------------------------------
-- credit_note
-- ---------------------------------------------------------------------------
CREATE TABLE credit_note (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id          bigint         NOT NULL,
    customer_id         bigint         NOT NULL,
    original_invoice_id bigint         NOT NULL,
    credit_note_number  varchar(50),
    status              varchar(20)    NOT NULL,
    credit_date         date,
    subtotal_amount     numeric(12, 2) NOT NULL DEFAULT 0,
    vat_amount          numeric(12, 2) NOT NULL DEFAULT 0,
    total_amount        numeric(12, 2) NOT NULL DEFAULT 0,
    reason              varchar(1000),
    created_at          timestamptz    NOT NULL DEFAULT now(),
    updated_at          timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT fk_credit_note_company  FOREIGN KEY (company_id)  REFERENCES company (id),
    CONSTRAINT fk_credit_note_customer FOREIGN KEY (customer_id) REFERENCES customer (id),
    -- RESTRICT on purpose: an invoice that has credit notes must never be
    -- deleted out from under them (and a SENT invoice is not deletable anyway).
    CONSTRAINT fk_credit_note_invoice  FOREIGN KEY (original_invoice_id)
        REFERENCES invoice (id) ON DELETE RESTRICT,
    CONSTRAINT ck_credit_note_status CHECK (status IN ('DRAFT', 'SENT')),
    CONSTRAINT ck_credit_note_number_when_sent CHECK (
        status = 'DRAFT' OR (credit_note_number IS NOT NULL AND credit_date IS NOT NULL)
    ),
    -- credit notes are stored with negative amounts
    CONSTRAINT ck_credit_note_amounts_not_positive CHECK (
        subtotal_amount <= 0 AND vat_amount <= 0 AND total_amount <= 0
    )
);

CREATE UNIQUE INDEX uq_credit_note_number_per_company
    ON credit_note (company_id, credit_note_number)
    WHERE credit_note_number IS NOT NULL;

CREATE INDEX ix_credit_note_company  ON credit_note (company_id);
CREATE INDEX ix_credit_note_customer ON credit_note (customer_id);
CREATE INDEX ix_credit_note_invoice  ON credit_note (original_invoice_id);

-- ---------------------------------------------------------------------------
-- credit_note_line
-- quantity and unit_price stay positive; the computed amounts are negative.
-- ---------------------------------------------------------------------------
CREATE TABLE credit_note_line (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_note_id  bigint         NOT NULL,
    position        int            NOT NULL,
    description     varchar(500)   NOT NULL,
    quantity        numeric(12, 3) NOT NULL,
    unit_price      numeric(12, 2) NOT NULL,
    vat_rate        numeric(5, 2)  NOT NULL,
    vat_type        varchar(20)    NOT NULL,
    line_net_amount numeric(12, 2) NOT NULL,
    line_vat_amount numeric(12, 2) NOT NULL,
    line_total      numeric(12, 2) NOT NULL,
    CONSTRAINT fk_credit_note_line_credit_note FOREIGN KEY (credit_note_id)
        REFERENCES credit_note (id) ON DELETE CASCADE,
    CONSTRAINT ck_credit_note_line_vat_type CHECK (
        vat_type IN ('STANDARD', 'REDUCED', 'ZERO', 'REVERSE_CHARGE')
    ),
    CONSTRAINT ck_credit_note_line_vat_rate CHECK (vat_rate >= 0),
    CONSTRAINT ck_credit_note_line_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_credit_note_line_unit_price_positive CHECK (unit_price >= 0),
    CONSTRAINT ck_credit_note_line_amounts_not_positive CHECK (
        line_net_amount <= 0 AND line_vat_amount <= 0 AND line_total <= 0
    ),
    CONSTRAINT uq_credit_note_line_position UNIQUE (credit_note_id, position)
);

CREATE INDEX ix_credit_note_line_credit_note ON credit_note_line (credit_note_id);

-- ---------------------------------------------------------------------------
-- number_sequence
-- one row per (company, document type, year); the row is locked and
-- incremented inside the transaction that assigns a definitive number.
-- ---------------------------------------------------------------------------
CREATE TABLE number_sequence (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id    bigint      NOT NULL,
    document_type varchar(20) NOT NULL,
    year          int         NOT NULL,
    last_value    int         NOT NULL DEFAULT 0,
    CONSTRAINT fk_number_sequence_company FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT ck_number_sequence_document_type CHECK (
        document_type IN ('INVOICE', 'CREDIT_NOTE')
    ),
    CONSTRAINT ck_number_sequence_last_value CHECK (last_value >= 0),
    CONSTRAINT uq_number_sequence UNIQUE (company_id, document_type, year)
);
